// Open Blog Article Detail Modal
function openBlogModal(slug) {
  const post = BLOGS_DATA.find(b => b.slug === slug);
  if (!post) return;

  // Generate Table of Contents items from Headings in markdown
  const headingMatches = post.content.match(/^#{1,3}\s+(.*)$/gm) || [];
  const headings = headingMatches.map(h => h.replace(/^#{1,3}\s+/, '').trim());

  // Render HTML from markdown roughly
  let parsedContent = post.content
    .replace(/^# (.*$)/gim, '<h1 id="$1" class="article-h1">$1</h1>')
    .replace(/^## (.*$)/gim, '<h2 id="$1" class="article-h2">$1</h2>')
    .replace(/^### (.*$)/gim, '<h3 id="$1" class="article-h3">$1</h3>')
    .replace(/^\-\-\-$/gim, '<hr class="article-hr">')
    .replace(/\*\*(.*?)\*\*/gim, '<strong>$1</strong>')
    .replace(/\*(.*?)\*/gim, '<em>$1</em>')
    .replace(/^- (.*$)/gim, '<li class="article-li">$1</li>')
    .replace(/\n\n/gim, '<br/><br/>');

  const modalOverlay = document.createElement('div');
  modalOverlay.className = 'blog-modal-overlay active';
  modalOverlay.id = 'blog-article-modal';

  modalOverlay.innerHTML = `
    <div class="blog-modal-container">
      
      <!-- Close Button -->
      <button class="blog-modal-close" onclick="closeBlogModal()">&times;</button>
      
      <!-- Modal Header Hero -->
      <div class="blog-modal-hero">
        <img src="${post.coverImage}" alt="${post.title}" class="blog-modal-hero__img">
        <div class="blog-modal-hero__overlay"></div>
        <div class="blog-modal-hero__content">
          <div class="blog-card__tags">
            ${post.tags.map(t => `<span class="blog-tag">${t}</span>`).join('')}
          </div>
          <h1 class="blog-modal-title">${post.title}</h1>
          <div class="blog-modal-author">
            <img src="${post.authorImage}" alt="${post.author}" class="author-avatar-img">
            <div>
              <p class="author-name">${post.author}</p>
              <p class="author-role">${post.authorRole}</p>
            </div>
            <span class="meta-divider">•</span>
            <p class="publish-date">${formatDate(post.publishedAt)}</p>
          </div>
        </div>
      </div>

      <!-- Modal Body (Grid with TOC + Article Content) -->
      <div class="blog-modal-body container">
        
        <!-- Sidebar TOC -->
        <aside class="blog-sidebar">
          ${headings.length > 0 ? `
            <div class="toc-card">
              <h4>Table of Contents</h4>
              <ul class="toc-list">
                ${headings.map(h => `<li><a href="#${h}" onclick="event.preventDefault(); scrollToHeading('${h}')">${h}</a></li>`).join('')}
              </ul>
            </div>
          ` : ''}

          <div class="share-card">
            <h4>Share this Article</h4>
            <div class="share-buttons">
              <button class="share-btn" onclick="shareArticle('${post.title}', 'whatsapp')">💬 WhatsApp</button>
              <button class="share-btn" onclick="shareArticle('${post.title}', 'copy')">📋 Copy Link</button>
            </div>
          </div>
        </aside>

        <!-- Main Article Text -->
        <article class="article-content">
          <p class="article-lead">${post.excerpt}</p>
          <div class="article-body">
            ${parsedContent}
          </div>

          <div class="article-footer">
            <p><strong>Little's Clinic – Pediatric & Child Centre</strong><br/>📍 Manipal County Road, Begur – Singasandra, Bangalore 560114<br/>📞 +91 7019204952 | ✉ littlesclinibengaluru@gmail.com</p>
            <button class="btn btn--primary" onclick="closeBlogModal(); document.querySelector('#contact').scrollIntoView({behavior: 'smooth'})">Book Appointment for Your Child</button>
          </div>
        </article>

      </div>

    </div>
  `;

  document.body.appendChild(modalOverlay);
  document.body.style.overflow = 'hidden';
}

function closeBlogModal() {
  const modal = document.getElementById('blog-article-modal');
  if (modal) {
    modal.remove();
    document.body.style.overflow = '';
  }
}

function scrollToHeading(headingId) {
  const el = document.getElementById(headingId);
  if (el) {
    el.scrollIntoView({ behavior: 'smooth' });
  }
}

function shareArticle(title, platform) {
  const url = window.location.href;
  if (platform === 'whatsapp') {
    window.open(`https://api.whatsapp.com/send?text=${encodeURIComponent(title + ' ' + url)}`, '_blank');
  } else {
    navigator.clipboard.writeText(url);
    alert('Article link copied to clipboard!');
  }
}

function formatDate(dateStr) {
  const options = { year: 'numeric', month: 'short', day: 'numeric' };
  return new Date(dateStr).toLocaleDateString('en-US', options);
}

